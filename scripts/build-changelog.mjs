#!/usr/bin/env node
//
// Builds CHANGELOG.md out of release_notes/.
//
// The release notes are the source and stay the source: each file is the body
// of one GitHub release, which is also what HACS shows in its update dialog.
// The changelog is a view of them, for the person upgrading across several
// versions at once - which is what a HACS upgrade usually is, because people
// update when they notice rather than when we tag.
//
//   npm run changelog          # write CHANGELOG.md
//   npm run changelog -- --check   # fail if it is out of date
//
// The check runs in CI. Without it the file drifts the first time a release
// note is edited after the fact.
//
// Deliberately no dates. They would have to come from the tags, `git log -1
// --format=%as v3.3.0` and so on, and a shallow checkout has no tags - the CI
// check would then produce a different file from the one written locally and
// fail for a reason that has nothing to do with the changelog. Each heading
// links to its release, which carries the date.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const notesDir = path.join(root, 'release_notes');
const target = path.join(root, 'CHANGELOG.md');
const releases = 'https://github.com/artem-sedykh/mini-climate-card/releases/tag';

const VERSION = /^v(\d+)\.(\d+)\.(\d+)\.md$/;

// The version this repository is at. Notes for anything beyond it are a draft
// for a release that has not happened - written early so the work is not
// forgotten, which is what `release_notes/` is for - and a changelog is a list
// of releases. Including them would link to a tag that does not exist yet.
//
// `release-prepare.yml` bumps this and rebuilds the changelog in one commit, so
// a version joins the list exactly when it becomes one.
const released = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
  .version.replace(/^v/, '')
  .split('.')
  .map(Number);

const isReleased = parts => {
  for (let i = 0; i < 3; i += 1) {
    if (parts[i] !== released[i]) return parts[i] < released[i];
  }
  return true;
};

const versions = readdirSync(notesDir)
  .map(file => ({ file, match: VERSION.exec(file) }))
  .filter(entry => {
    if (!entry.match) {
      // Anything else is either a pre-release (`v2.5.3.beta.1` has a tag but no
      // notes) or a mistake. Say so rather than dropping it in silence.
      if (entry.file.endsWith('.md'))
        console.warn(`Skipping ${entry.file}: not vMAJOR.MINOR.PATCH`);
      return false;
    }

    const parts = [1, 2, 3].map(i => Number(entry.match[i]));
    if (isReleased(parts)) return true;

    console.warn(`Skipping ${entry.file}: ahead of package.json, not released yet`);
    return false;
  })
  // Newest first, and by number rather than by name: sorted as strings,
  // `v2.10.0` comes before `v2.2.1`.
  .sort((a, b) => {
    for (let i = 1; i <= 3; i += 1) {
      const diff = Number(b.match[i]) - Number(a.match[i]);
      if (diff !== 0) return diff;
    }
    return 0;
  });

if (versions.length === 0) {
  console.error(`No release notes in ${path.relative(root, notesDir)}.`);
  process.exit(1);
}

const body = versions
  .map(({ file, match }) => {
    const version = `v${match[1]}.${match[2]}.${match[3]}`;
    const notes = readFileSync(path.join(notesDir, file), 'utf8')
      .replace(/\r\n/g, '\n')
      // The older notes open with a heading of their own version, which the
      // heading below would repeat. The newer ones start straight at the
      // content, which is what AGENTS.md asks for.
      // Escaping the dots alone was enough for what VERSION can produce - three
      // runs of digits - but it reads as a complete escape without being one.
      // Every metacharacter is escaped instead, so the line stays correct if
      // that pattern ever admits more than digits.
      .replace(new RegExp(`^#{1,3} +${version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')} *\n+`), '')
      .trim();

    return `## [${version}](${releases}/${version})\n\n${notes}\n`;
  })
  .join('\n');

const content = `<!--
  Generated by scripts/build-changelog.mjs from release_notes/. Do not edit.
  To change what a release says, edit its file in release_notes/ and run
  \`npm run changelog\`.
-->

# Changelog

Every release of this card, newest first. Each heading links to the release it
came from, where the asset and the date are.

${body}`;

const current = (() => {
  try {
    return readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    return null;
  }
})();

if (process.argv.includes('--check')) {
  if (current === content) {
    console.log(`OK: CHANGELOG.md is up to date (${versions.length} releases).`);
    process.exit(0);
  }

  console.error(
    current === null
      ? 'CHANGELOG.md is missing. Run `npm run changelog`.'
      : 'CHANGELOG.md does not match release_notes/. Run `npm run changelog` and commit it.',
  );
  process.exit(1);
}

writeFileSync(target, content);
console.log(`Wrote CHANGELOG.md, ${versions.length} releases.`);
